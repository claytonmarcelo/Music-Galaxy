    0xF4, 0xCD, 0x0A, 0xA5, 0x00, 0x00, 0x00, 0x09, // ...
    0x70, 0x48, 0x59, 0x73, 0x00, 0x00, 0x0B, 0x13, // pHYs (DPI)
    0x00, 0x00, 0x0B, 0x13, 0x01, 0x00, 0x9A, 0x9C, // ...
    0x18, 0x00, 0x00, 0x00, 0x36, 0x49, 0x44, 0x41, // IDAT
    0x54, 0x78, 0x9C, 0xED, 0xC1, 0x31, 0x0D, 0x00, // x...1..
    0x00, 0x00, 0xC2, 0xA0, 0xF5, 0x4F, 0xED, 0x61, // ...O.a
